#!/usr/bin/env python3
"""Ambil data di web untuk Nykripsi v2: curl-first, eskalasi ke headless
(puppeteer/chrome) bila halaman kacau (JS-rendered), ekstrak teks bersih,
lalu arsipkan dengan provenance.

Skrip ini tanpa dependensi pihak ketiga (hanya pustaka standar Python 3).
Tangga pengambilan (rung 1-2):

    rung 1  curl -sSL          -- cepat, hemat, untuk HTML statis
    rung 2  headless puppeteer -- bila halaman JS-rendered / kacau
            headless chrome    -- cadangan bila puppeteer tidak tersedia

Program eksternal yang dipakai: ``curl``, ``pandoc``, ``node``, dan biner
Chrome (Chrome for Testing). Baris provenance ``# backend: <name>`` dicetak ke
stderr agar stdout tetap bersih.

Contoh:
    python3 tools/webgrab.py fetch https://example.com
    python3 tools/webgrab.py fetch "file:///tmp/chaos.html" --force-headless
    python3 tools/webgrab.py discover "vaccine diplomacy" --limit 3
    python3 tools/webgrab.py discover "vaccine diplomacy" --fetch
    python3 tools/webgrab.py render

PERINGATAN: jangan pernah mengarang teks, status, atau URL. Bila halaman tidak
dapat diambil, statusnya jujur (``http-<kode>`` / ``error`` /
``chaotic-unresolved``) — bukan data palsu. Berkas mentah dan teks tersimpan di
``docs/web-corpus/`` dan dicatat pada ``manifest.tsv``.

# backend: webgrab
"""

import argparse
import datetime
import glob
import hashlib
import html
import json
import os
import re
import shutil
import subprocess
import sys
import tempfile
import unicodedata

BACKEND = "webgrab"

UA = "Mozilla/5.0 (X11; Linux x86_64) (Nykripsi research; mailto:research@example.com)"
OUTDIR = "docs/web-corpus"
MANIFEST = "docs/web-corpus/manifest.tsv"
MANIFEST_MD = "docs/web-corpus/MANIFEST.md"
HEADER = ["slug", "url", "accessed", "mode", "status", "http", "bytes", "sha256", "text_chars"]
MODES = ("curl", "headless-puppeteer", "headless-chrome")
CURL_TIMEOUT = 30          # seconds, curl --max-time
HEADLESS_TIMEOUT = 45000   # ms, puppeteer goto timeout
CHROME_BUDGET = 8000       # ms, chrome --virtual-time-budget
MD_HEADER = "<!-- generated by webgrab.py render; edit docs/web-corpus/manifest.tsv, not this file -->"
SPA_RE = re.compile(
    r'id=["\'](?:root|app|__next|__nuxt)["\']|__NEXT_DATA__|__NUXT__|'
    r'data-reactroot|ng-version|v-app|id=["\']svelte["\']', re.I)
JSREQ_RE = re.compile(r"enable javascript|requires javascript|you need to enable javascript", re.I)
SCRIPT_RE = re.compile(r"(?is)<script\b")
TAG_RE = re.compile(r"(?s)<[^>]+>")
BLOCK_RE = re.compile(r"(?is)<(script|style|noscript)[^>]*>.*?</\1>")

SEARCH = ".claude/skills/nykripsi/scripts/search.py"

_HEADLESS_DRIVER = """const fs = require('fs');
const puppeteer = require('puppeteer');
(async () => {
  const [url, out, t] = process.argv.slice(2);
  const browser = await puppeteer.launch({
    executablePath: process.env.PUPPETEER_EXECUTABLE_PATH || undefined,
    headless: 'new',
    args: ['--no-sandbox', '--disable-gpu', '--no-first-run', '--disable-dev-shm-usage'],
  });
  try {
    const page = await browser.newPage();
    await page.goto(url, { waitUntil: 'networkidle2', timeout: Number(t) || 45000 });
    fs.writeFileSync(out, await page.content(), 'utf8');
  } finally { await browser.close(); }
})().catch((e) => { console.error(String(e)); process.exit(1); });
"""

# ---------------------------------------------------------------------------
# Utilitas umum
# ---------------------------------------------------------------------------

def _log_provenance(name: str, to_stderr: bool = True) -> None:
    """Cetak baris provenance ``# backend: <name>``."""
    stream = sys.stderr if to_stderr else sys.stdout
    print(f"# backend: {name}", file=stream)

def _slug(url: str) -> str:
    """ASCII-fold URL (buang skema http/https) -> lowercase -> ``[^a-z0-9]+``
    -> ``-`` -> strip ``-``. Kosong -> ``untitled``."""
    text = re.sub(r"^https?://", "", url, flags=re.I)
    text = unicodedata.normalize("NFKD", text).encode("ascii", "ignore").decode()
    text = text.lower()
    text = re.sub(r"[^a-z0-9]+", "-", text)
    return text.strip("-") or "untitled"

def _visible(html_text: str) -> str:
    """Perkiraan teks terlihat: buang blok script/style/noscript, buang tag,
    unescape entitas, lalu rapikan spasi."""
    t = BLOCK_RE.sub(" ", html_text)
    t = TAG_RE.sub(" ", t)
    t = html.unescape(t)
    return re.sub(r"\s+", " ", t).strip()

def _is_chaotic(html_text: str) -> bool:
    """True bila halaman tampak JS-rendered / kacau (kandidat eskalasi)."""
    if SPA_RE.search(html_text):
        return True
    if JSREQ_RE.search(html_text):
        return True
    if len(SCRIPT_RE.findall(html_text)) >= 3 and len(_visible(html_text)) < 200:
        return True
    if len(_visible(html_text)) < 50 and len(html_text.encode("utf-8")) > 2000:
        return True
    return False

def _sha256(data: bytes) -> str:
    """Digest SHA-256 64-hex dari ``data``."""
    return hashlib.sha256(data).hexdigest()

def _today() -> str:
    """Tanggal akses ISO (YYYY-MM-DD)."""
    return datetime.date.today().isoformat()

def _find_chrome() -> str | None:
    """Biner Chrome terbaru (puppeteer cache) atau dari PATH; ``None`` bila tiada."""
    pattern = os.path.expanduser("~/.cache/puppeteer/chrome/*/chrome-linux64/chrome")
    cands = [p for p in glob.glob(pattern) if os.path.isfile(p)]
    if cands:
        return max(cands, key=os.path.getmtime)
    for name in ("chromium", "chromium-browser", "google-chrome", "google-chrome-stable", "chrome"):
        found = shutil.which(name)
        if found:
            return found
    return None

def _find_puppeteer_nm() -> str | None:
    """Direktori ``node_modules`` (npx cache) yang memuat puppeteer; ``None`` bila tiada."""
    pattern = os.path.expanduser("~/.npm/_npx/*/node_modules/puppeteer/package.json")
    cands = glob.glob(pattern)
    if not cands:
        return None
    newest = max(cands, key=os.path.getmtime)
    return os.path.dirname(os.path.dirname(newest))

def _unlink(path: str) -> None:
    try:
        os.remove(path)
    except OSError:
        pass

# ---------------------------------------------------------------------------
# Rung 1: curl
# ---------------------------------------------------------------------------

def _curl(url: str) -> tuple[int, bytes, str]:
    """Ambil ``url`` dengan curl -> (status, body, err).

    Tanpa ``-f`` supaya body pada 4xx/5xx tetap tersimpan. Kembalikan
    ``(0, b"", pesan)`` bila curl tidak tersedia atau keluar non-nol."""
    fd, tmp = tempfile.mkstemp(prefix="webgrab-body-", suffix=".bin")
    os.close(fd)
    try:
        try:
            proc = subprocess.run(
                ["curl", "-sSL", "-A", UA, "--max-time", str(CURL_TIMEOUT),
                 "-o", tmp, "-w", "%{http_code}", url],
                capture_output=True, text=True)
        except OSError as exc:
            return 0, b"", str(exc)
        if proc.returncode != 0:
            return 0, b"", f"curl exit {proc.returncode}: {(proc.stderr or '').strip()}"
        code = (proc.stdout or "").strip()
        try:
            status = int(code) if code else 0
        except ValueError:
            status = 0
        try:
            with open(tmp, "rb") as fh:
                body = fh.read()
        except OSError as exc:
            return 0, b"", str(exc)
        return status, body, ""
    finally:
        _unlink(tmp)

# ---------------------------------------------------------------------------
# Rung 2: headless (puppeteer lalu chrome)
# ---------------------------------------------------------------------------

def _headless_puppeteer(url: str) -> str | None:
    """Render ``url`` lewat node+puppeteer -> HTML DOM; ``None`` bila gagal."""
    nm = _find_puppeteer_nm()
    chrome = _find_chrome()
    if nm is None or chrome is None:
        return None
    dfd, driver = tempfile.mkstemp(prefix="webgrab-driver-", suffix=".cjs")
    os.close(dfd)
    ofd, out = tempfile.mkstemp(prefix="webgrab-dom-", suffix=".html")
    os.close(ofd)
    try:
        with open(driver, "w", encoding="utf-8") as fh:
            fh.write(_HEADLESS_DRIVER)
        env = {**os.environ, "NODE_PATH": nm, "PUPPETEER_EXECUTABLE_PATH": chrome}
        try:
            proc = subprocess.run(
                ["node", driver, url, out, str(HEADLESS_TIMEOUT)],
                env=env, capture_output=True, timeout=120)
        except (OSError, subprocess.SubprocessError):
            return None
        if proc.returncode != 0:
            return None
        try:
            with open(out, "r", encoding="utf-8", errors="replace") as fh:
                text = fh.read()
        except OSError:
            return None
        return text or None
    finally:
        _unlink(driver)
        _unlink(out)

def _headless_chrome(url: str) -> str | None:
    """Render ``url`` lewat ``chrome --headless=new --dump-dom``; ``None`` bila gagal."""
    chrome = _find_chrome()
    if chrome is None:
        return None
    try:
        proc = subprocess.run(
            [chrome, "--headless=new", "--no-sandbox", "--disable-gpu",
             "--virtual-time-budget=" + str(CHROME_BUDGET), "--dump-dom", url],
            capture_output=True, timeout=120)
    except (OSError, subprocess.SubprocessError):
        return None
    if proc.returncode != 0:
        return None
    return proc.stdout.decode("utf-8", "replace")

def _escalate(url: str) -> tuple[str | None, str | None]:
    """Coba rung 2: puppeteer lalu chrome -> (teks, mode)."""
    text = _headless_puppeteer(url)
    if text is not None:
        return text, "headless-puppeteer"
    text = _headless_chrome(url)
    if text is not None:
        return text, "headless-chrome"
    return None, None

# ---------------------------------------------------------------------------
# Ekstraksi teks
# ---------------------------------------------------------------------------

def _extract(body: bytes) -> tuple[str, str]:
    """Klasifikasi + ekstraksi teks -> (kind, text). kind = pdf|json|html."""
    if body[:5] == b"%PDF-":
        text = ""
        if shutil.which("pdftotext"):
            try:
                proc = subprocess.run(["pdftotext", "-", "-"], input=body,
                                      capture_output=True, timeout=120)
                if proc.returncode == 0:
                    text = proc.stdout.decode("utf-8", "replace")
            except (OSError, subprocess.SubprocessError):
                text = ""
        return "pdf", text

    decoded = body.decode("utf-8", "replace")
    if decoded.lstrip()[:1] in ("{", "["):
        return "json", decoded

    try:
        proc = subprocess.run(["pandoc", "-f", "html", "-t", "plain"],
                              input=decoded, capture_output=True, text=True, timeout=120)
        if proc.returncode == 0:
            return "html", proc.stdout or ""
    except (OSError, subprocess.SubprocessError):
        pass
    return "html", _visible(decoded)

# ---------------------------------------------------------------------------
# Inti: grab
# ---------------------------------------------------------------------------

def _grab(url: str, force_headless: bool = False, outdir: str = OUTDIR) -> dict:
    """Ambil ``url`` (curl-first, eskalasi headless) lalu arsipkan.

    Kembalikan dict record (lihat ``HEADER``). Tidak pernah mengarang data."""
    slug = _slug(url)
    mode = "curl"
    headless_unavailable = False
    status, body = 0, b""

    if not force_headless and shutil.which("curl") is None:
        # curl tidak tersedia: catat baris jujur tanpa berkas.
        return {
            "slug": slug, "url": url, "accessed": _today(), "mode": mode,
            "status": "error", "http": 0, "bytes": 0,
            "sha256": _sha256(b""), "text_chars": 0,
        }

    if force_headless:
        text, hmode = _escalate(url)
        if text is not None:
            body = text.encode("utf-8")
            mode = hmode
            status = 200
        else:
            headless_unavailable = True
    else:
        status, body, _err = _curl(url)
        escalate = status != 200
        if not escalate and body:
            if _is_chaotic(body.decode("utf-8", "replace")):
                escalate = True
        if escalate:
            text, hmode = _escalate(url)
            if text is not None:
                body = text.encode("utf-8")
                mode = hmode
                status = 200
            else:
                headless_unavailable = True

    kind, text = _extract(body)

    os.makedirs(outdir, exist_ok=True)
    if body:
        ext = {"pdf": "pdf", "json": "json", "html": "html"}[kind]
        raw_path = os.path.join(outdir, f"{slug}.{ext}")
        try:
            with open(raw_path, "wb") as fh:
                fh.write(body)
        except OSError:
            pass
        if text:
            txt_path = os.path.join(outdir, f"{slug}.txt")
            try:
                with open(txt_path, "w", encoding="utf-8") as fh:
                    fh.write(text)
            except OSError:
                pass

    if not body:
        if status == 200:
            status_str = "empty"
        elif status:
            status_str = f"http-{status}"
        else:
            status_str = "error"
    else:
        if status == 200 and (text or kind != "html"):
            status_str = "ok"
        elif status:
            status_str = f"http-{status}"
        else:
            status_str = "error"
        if headless_unavailable and _is_chaotic(body.decode("utf-8", "replace")):
            status_str = "chaotic-unresolved"

    return {
        "slug": slug,
        "url": url,
        "accessed": _today(),
        "mode": mode,
        "status": status_str,
        "http": status,
        "bytes": len(body),
        "sha256": _sha256(body),
        "text_chars": len(text),
    }

# ---------------------------------------------------------------------------
# Manifest I/O (gaya atomik libgen.py)
# ---------------------------------------------------------------------------

def _read_manifest(path: str) -> list[dict]:
    """Baca manifest TSV -> daftar dict. ``[]`` bila tidak ada."""
    if not os.path.exists(path):
        return []
    with open(path, encoding="utf-8") as fh:
        lines = [ln.rstrip("\n") for ln in fh if ln.strip()]
    if not lines:
        return []
    if lines[0] != "\t".join(HEADER):
        raise ValueError(f"header manifest tidak dikenal: {lines[0]!r}")
    rows: list[dict] = []
    for line in lines[1:]:
        cells = line.split("\t")
        row = {key: (cells[i] if i < len(cells) else "") for i, key in enumerate(HEADER)}
        rows.append(row)
    return rows

def _write_manifest(path: str, rows: list[dict]) -> None:
    """Tulis manifest TSV secara atomik (tulis ``.tmp`` lalu ``os.replace``)."""
    directory = os.path.dirname(path)
    if directory:
        os.makedirs(directory, exist_ok=True)
    tmp = path + ".tmp"
    with open(tmp, "w", encoding="utf-8") as fh:
        fh.write("\t".join(HEADER) + "\n")
        for row in rows:
            fh.write("\t".join(str(row.get(key, "")) for key in HEADER) + "\n")
    os.replace(tmp, path)

def _upsert(rows: list[dict], rec: dict) -> list[dict]:
    """Ganti baris dengan ``slug`` sama; selain itu tambahkan. Urutan dipertahankan."""
    for i, row in enumerate(rows):
        if row.get("slug") == rec.get("slug"):
            rows[i] = rec
            return rows
    rows.append(rec)
    return rows

# ---------------------------------------------------------------------------
# Render MANIFEST.md
# ---------------------------------------------------------------------------

def _render_manifest(manifest_path: str, md_path: str = MANIFEST_MD) -> str:
    """Tulis ``MANIFEST.md`` dari manifest TSV; kembalikan path."""
    rows = _read_manifest(manifest_path)
    lines = [MD_HEADER, ""]
    lines.append("| # | slug | url | accessed | mode | status | bytes | text_chars |")
    lines.append("| --- | --- | --- | --- | --- | --- | --- | --- |")
    ok = failed = 0
    cols = ("slug", "url", "accessed", "mode", "status", "bytes", "text_chars")
    for i, row in enumerate(rows, start=1):
        cells = [str(row.get(key, "")).replace("|", "\\|") for key in cols]
        lines.append("| " + str(i) + " | " + " | ".join(cells) + " |")
        if row.get("status") == "ok":
            ok += 1
        else:
            failed += 1
    lines.append("")
    lines.append(f"OK={ok} FAILED={failed}")
    directory = os.path.dirname(md_path)
    if directory:
        os.makedirs(directory, exist_ok=True)
    tmp = md_path + ".tmp"
    with open(tmp, "w", encoding="utf-8") as fh:
        fh.write("\n".join(lines) + "\n")
    os.replace(tmp, md_path)
    return md_path

# ---------------------------------------------------------------------------
# Perintah: fetch
# ---------------------------------------------------------------------------

def cmd_fetch(args) -> int:
    _log_provenance(BACKEND, to_stderr=True)
    rec = _grab(args.url, force_headless=args.force_headless, outdir=args.out)
    try:
        rows = _read_manifest(args.manifest)
    except (OSError, ValueError) as exc:
        print(f"GAGAL: manifest tidak dapat dibaca ({exc})", file=sys.stderr)
        rows = []
    rows = _upsert(rows, rec)
    try:
        _write_manifest(args.manifest, rows)
    except OSError as exc:
        print(f"GAGAL: manifest tidak dapat ditulis ({exc})", file=sys.stderr)
    try:
        _render_manifest(args.manifest, MANIFEST_MD)
    except (OSError, ValueError) as exc:
        print(f"GAGAL: render gagal ({exc})", file=sys.stderr)
    if args.json:
        print(json.dumps(rec, ensure_ascii=False))
    else:
        print(f"WEBGRAB: {rec['slug']} mode={rec['mode']} status={rec['status']} "
              f"http={rec['http']} text={rec['text_chars']}")
    return 0 if rec["status"] == "ok" else 1

# ---------------------------------------------------------------------------
# Perintah: discover
# ---------------------------------------------------------------------------

def cmd_discover(args) -> int:
    _log_provenance(BACKEND, to_stderr=True)
    cmd = [sys.executable, SEARCH, args.subcmd, args.query,
           "--limit", str(args.limit), "--json", "--no-save",
           "--registry", "/dev/null"]
    try:
        proc = subprocess.run(cmd, capture_output=True, text=True, timeout=180)
    except (OSError, subprocess.SubprocessError) as exc:
        print(f"GAGAL: search.py tidak dapat dijalankan ({exc})", file=sys.stderr)
        return 0
    urls: list[str] = []
    seen: set[str] = set()
    try:
        data = json.loads(proc.stdout)
    except ValueError:
        data = []
    if isinstance(data, list):
        for rec in data:
            if not isinstance(rec, dict):
                continue
            url = str(rec.get("url") or "").strip()
            if url and url not in seen:
                seen.add(url)
                urls.append(url)
    for url in urls:
        print(url)
    if args.fetch and urls:
        try:
            rows = _read_manifest(args.manifest)
        except (OSError, ValueError) as exc:
            print(f"GAGAL: manifest tidak dapat dibaca ({exc})", file=sys.stderr)
            rows = []
        for url in urls:
            rec = _grab(url, outdir=args.out)
            rows = _upsert(rows, rec)
            print(f"# backend: {BACKEND} {rec['slug']} mode={rec['mode']} "
                  f"status={rec['status']}", file=sys.stderr)
        try:
            _write_manifest(args.manifest, rows)
            _render_manifest(args.manifest, MANIFEST_MD)
        except (OSError, ValueError) as exc:
            print(f"GAGAL: manifest/render gagal ({exc})", file=sys.stderr)
    return 0

# ---------------------------------------------------------------------------
# Perintah: render
# ---------------------------------------------------------------------------

def cmd_render(args) -> int:
    _log_provenance(BACKEND, to_stderr=True)
    try:
        path = _render_manifest(args.manifest, args.md)
    except (OSError, ValueError) as exc:
        print(f"GAGAL: render gagal ({exc})", file=sys.stderr)
        return 1
    print(path)
    return 0

# ---------------------------------------------------------------------------
# CLI
# ---------------------------------------------------------------------------

def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(
        prog="webgrab",
        description="Ambil web curl-first, eskalasi headless bila kacau, arsipkan + provenance.",
    )
    parser.add_argument("--version", action="version", version="webgrab 0.1")
    sub = parser.add_subparsers(dest="command")

    p_fetch = sub.add_parser("fetch", help="ambil satu URL dan arsipkan")
    p_fetch.add_argument("url")
    p_fetch.add_argument("--force-headless", action="store_true",
                         help="lewati curl, langsung rung 2 (puppeteer/chrome)")
    p_fetch.add_argument("--out", default=OUTDIR, help=f"direktori keluaran (default: {OUTDIR})")
    p_fetch.add_argument("--manifest", default=MANIFEST,
                         help=f"berkas manifest (default: {MANIFEST})")
    p_fetch.add_argument("--json", action="store_true", help="cetak record sebagai JSON")
    p_fetch.set_defaults(func=cmd_fetch)

    p_discover = sub.add_parser("discover", help="cari URL lewat search.py lalu opsional fetch")
    p_discover.add_argument("query")
    p_discover.add_argument("--limit", type=int, default=5, help="jumlah maksimum hasil (default: 5)")
    p_discover.add_argument("--subcmd", choices=("web", "news"), default="web",
                            help="subperintah search.py (default: web)")
    p_discover.add_argument("--fetch", action="store_true", help="fetch setiap URL hasil")
    p_discover.add_argument("--out", default=OUTDIR, help=f"direktori keluaran (default: {OUTDIR})")
    p_discover.add_argument("--manifest", default=MANIFEST,
                            help=f"berkas manifest (default: {MANIFEST})")
    p_discover.set_defaults(func=cmd_discover)

    p_render = sub.add_parser("render", help="tulis ulang MANIFEST.md dari manifest.tsv")
    p_render.add_argument("--manifest", default=MANIFEST,
                          help=f"berkas manifest (default: {MANIFEST})")
    p_render.add_argument("--md", default=MANIFEST_MD,
                          help=f"berkas markdown (default: {MANIFEST_MD})")
    p_render.set_defaults(func=cmd_render)

    return parser

def main(argv: list[str] | None = None) -> int:
    parser = build_parser()
    args = parser.parse_args(argv)
    if not getattr(args, "command", None):
        parser.print_help()
        return 0
    try:
        return args.func(args)
    except KeyboardInterrupt:
        return 130

if __name__ == "__main__":
    sys.exit(main())
