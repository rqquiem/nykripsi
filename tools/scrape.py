#!/usr/bin/env python3
"""Alat sapuan subjek: kumpulkan seluruh materi sekunder tentang subjek.

Stdlib saja. Contoh:
    python3 tools/scrape.py add "PT Contoh" --aliases "Contoh Corp,Contoh"
    python3 tools/scrape.py sweep "PT Contoh"
    python3 tools/scrape.py render
"""

import argparse
import datetime
import json
import os
import re
import subprocess
import sys
import unicodedata

# Akar repo: tools/scrape.py -> tools -> root.
REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SEARCH = os.path.join(REPO, ".claude", "skills", "nykripsi", "scripts", "search.py")
DEFAULT_REGISTRY = "subjects/registry.json"
DEFAULT_INDEX = "subjects/index.md"
DEFAULT_SOURCES = "sources/registry.json"
CHANNELS = ("press", "news", "article", "official", "web")
CHANNEL_SEARCH = {
    "press":    ("web",     "{name} press release"),
    "news":     ("news",    "{name}"),
    "article":  ("article", "{name}"),
    "official": ("company", "{name}"),
    "web":      ("web",     "{name}"),
}
DEFAULT_K = 3
STATUSES = ("incomplete", "complete")
TAMBAH_RE = re.compile(r"TAMBAH:\s+(\d+)\s+baru")
HEADER = "<!-- generated by scrape.py render; edit subjects/registry.json, not this file -->"


# ---------------------------------------------------------------------------
# Bantuan
# ---------------------------------------------------------------------------

def _slug(text: str) -> str:
    """ASCII-fold -> huruf kecil -> hanya ``[a-z0-9-]``."""
    folded = unicodedata.normalize("NFKD", text or "").encode("ascii", "ignore").decode("ascii")
    folded = re.sub(r"[^a-z0-9]+", "-", folded.lower()).strip("-")
    return folded or "untitled"


def _load_registry(path: str) -> list[dict]:
    if not os.path.exists(path):
        return []
    with open(path, encoding="utf-8") as fh:
        text = fh.read().strip()
    if not text:
        return []
    data = json.loads(text)
    if not isinstance(data, list):
        raise ValueError(f"{path} bukan array JSON")
    return data


def _write_registry(path: str, registry: list[dict]) -> None:
    directory = os.path.dirname(path)
    if directory:
        os.makedirs(directory, exist_ok=True)
    with open(path, "w", encoding="utf-8") as fh:
        fh.write(json.dumps(registry, ensure_ascii=False, indent=2) + "\n")


def _assign_id(name: str, accessed: str, registry: list[dict]) -> str:
    used = {r.get("id") for r in registry if isinstance(r, dict)}
    base = f"subject-{accessed}-{_slug(name)}"
    candidate = base
    n = 0
    while candidate in used:
        n += 1
        candidate = f"{base}-{n}"
    return candidate


def _cell(value) -> str:
    """Rapikan isi sel tabel Markdown."""
    return str(value if value is not None else "").replace("|", "\\|").replace("\n", " ").strip()


def _today() -> str:
    return datetime.date.today().isoformat()


def _find_subject(registry: list[dict], name: str) -> dict | None:
    for rec in registry:
        if isinstance(rec, dict) and rec.get("name") == name:
            return rec
    return None


# ---------------------------------------------------------------------------
# Subperintah
# ---------------------------------------------------------------------------

def cmd_add(args) -> int:
    registry = _load_registry(args.registry)

    if _find_subject(registry, args.name) is not None:
        print(f"GAGAL: subjek '{args.name}' sudah ada")
        return 1

    accessed = _today()
    aliases = [a.strip() for a in (args.aliases or "").split(",") if a.strip()]
    rid = _assign_id(args.name, accessed, registry)
    record = {
        "id": rid,
        "name": args.name,
        "aliases": aliases,
        "accessed": accessed,
        "channels": {ch: {"required": True, "count": 0} for ch in CHANNELS},
        "queries": [],
        "saturation": {"k": args.k, "barren_rounds": 0, "saturated": False},
        "status": "incomplete",
        "notes": "",
    }
    registry.append(record)
    _write_registry(args.registry, registry)
    print(f"TAMBAH: subjek '{args.name}' ({rid})")
    return 0


def cmd_sweep(args) -> int:
    registry = _load_registry(args.registry)
    rec = _find_subject(registry, args.name)
    if rec is None:
        print(f"GAGAL: subjek '{args.name}' tidak ada; jalankan 'add' dulu")
        return 1

    channels = rec.setdefault("channels", {})
    queries = rec.setdefault("queries", [])
    saturation = rec.setdefault("saturation", {"k": DEFAULT_K, "barren_rounds": 0, "saturated": False})
    k = saturation.get("k", DEFAULT_K)

    selected = [args.channel] if args.channel else list(CHANNELS)
    rounds = args.rounds if args.rounds and args.rounds > 0 else 1
    round_new = 0

    for _round in range(rounds):
        round_new = 0
        for ch in selected:
            subcmd, query_tpl = CHANNEL_SEARCH[ch]
            query = query_tpl.format(name=args.name)
            cmd = [sys.executable, SEARCH, subcmd, query,
                   "--limit", str(args.limit), "--registry", args.sources,
                   "--subject", args.name, "--channel", ch]
            if args.email:
                cmd += ["--email", args.email]
            try:
                proc = subprocess.run(cmd, capture_output=True, text=True)
                out = (proc.stdout or "") + (proc.stderr or "")
            except OSError as exc:  # kegagalan jaringan/proses: non-fatal
                print(f"CATATAN: kanal '{ch}' gagal dijalankan ({exc})", file=sys.stderr)
                out = ""
            match = TAMBAH_RE.search(out)
            n = int(match.group(1)) if match else 0

            chrec = channels.setdefault(ch, {"required": True, "count": 0})
            chrec["count"] = chrec.get("count", 0) + n
            if query not in queries:
                queries.append(query)
            round_new += n

        if round_new == 0:
            saturation["barren_rounds"] = saturation.get("barren_rounds", 0) + 1
        else:
            saturation["barren_rounds"] = 0

    saturated = saturation.get("barren_rounds", 0) >= k
    saturation["saturated"] = saturated

    complete = all(
        channels.get(ch, {}).get("count", 0) >= 1
        for ch in CHANNELS
        if channels.get(ch, {}).get("required", True)
    ) and saturated
    rec["status"] = "complete" if complete else "incomplete"

    _write_registry(args.registry, registry)

    counts = ", ".join(f"{ch}={channels.get(ch, {}).get('count', 0)}" for ch in CHANNELS)
    print(f"SWEEP: {args.name} — {counts}; baru={round_new}; saturasi={saturated}")
    return 0


def cmd_render(args) -> int:
    registry = _load_registry(args.registry)

    lines = [HEADER, ""]
    if not registry:
        lines.append("_Belum ada subjek._")
    else:
        lines.append("| id | subjek | status | press | news | article | official | web | saturasi | diakses |")
        lines.append("| --- | --- | --- | --- | --- | --- | --- | --- | --- | --- |")
        for rec in registry:
            if not isinstance(rec, dict):
                continue
            channels = rec.get("channels") or {}
            saturation = rec.get("saturation") or {}
            cells = [
                _cell(rec.get("id")),
                _cell(rec.get("name")),
                _cell(rec.get("status")),
            ]
            for ch in CHANNELS:
                chrec = channels.get(ch) or {}
                cells.append(_cell(chrec.get("count", 0)))
            cells.append(_cell(saturation.get("saturated")))
            cells.append(_cell(rec.get("accessed")))
            lines.append("| " + " | ".join(cells) + " |")

    directory = os.path.dirname(args.index)
    if directory:
        os.makedirs(directory, exist_ok=True)
    with open(args.index, "w", encoding="utf-8") as fh:
        fh.write("\n".join(lines).rstrip("\n") + "\n")
    print(args.index)
    return 0


# ---------------------------------------------------------------------------
# CLI
# ---------------------------------------------------------------------------

def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(
        prog="scrape.py",
        description="Sapu seluruh materi sekunder tentang subjek penelitian.",
    )
    sub = parser.add_subparsers(dest="command")

    p_add = sub.add_parser("add", help="deklarasikan subjek baru")
    p_add.add_argument("name", help="nama subjek")
    p_add.add_argument("--aliases", default="", help="alias dipisah koma")
    p_add.add_argument("--k", type=int, default=DEFAULT_K,
                       help=f"K saturasi (default: {DEFAULT_K})")
    p_add.add_argument("--registry", default=DEFAULT_REGISTRY,
                       help=f"berkas registry (default: {DEFAULT_REGISTRY})")
    p_add.set_defaults(func=cmd_add)

    p_sweep = sub.add_parser("sweep", help="sapu kanal sekunder sebuah subjek")
    p_sweep.add_argument("name", help="nama subjek")
    p_sweep.add_argument("--channel", default=None, choices=CHANNELS,
                         help="sapu satu kanal saja (default: semua kanal)")
    p_sweep.add_argument("--rounds", type=int, default=1,
                         help="jumlah putaran (default: 1)")
    p_sweep.add_argument("--registry", default=DEFAULT_REGISTRY,
                         help=f"berkas registry subjek (default: {DEFAULT_REGISTRY})")
    p_sweep.add_argument("--sources", default=DEFAULT_SOURCES,
                         help=f"berkas registry sumber (default: {DEFAULT_SOURCES})")
    p_sweep.add_argument("--limit", type=int, default=10,
                         help="hasil maksimum per kueri (default: 10)")
    p_sweep.add_argument("--email", default=None, help="alamat surel polite pool")
    p_sweep.set_defaults(func=cmd_sweep)

    p_render = sub.add_parser("render", help="tulis ulang subjects/index.md dari registry")
    p_render.add_argument("--registry", default=DEFAULT_REGISTRY,
                          help=f"berkas registry (default: {DEFAULT_REGISTRY})")
    p_render.add_argument("--index", default=DEFAULT_INDEX,
                          help=f"berkas indeks (default: {DEFAULT_INDEX})")
    p_render.set_defaults(func=cmd_render)

    return parser


def main(argv: list[str] | None = None) -> int:
    parser = build_parser()
    args = parser.parse_args(argv)
    if getattr(args, "command", None) is None:
        parser.print_help()
        return 0
    try:
        return args.func(args)
    except KeyboardInterrupt:
        return 130


if __name__ == "__main__":
    sys.exit(main())
