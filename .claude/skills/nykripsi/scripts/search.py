    override = getattr(args, "source_class", None)
    updated = 0
    for rec in registry:
        if not isinstance(rec, dict):
            continue
        if override:
            rec["source_class"] = override
            rec["class_origin"] = "manual"
            updated += 1
            continue
        if rec.get("class_origin") == "manual":
            continue
        rec["source_class"] = default_class(rec.get("type"))
        rec["class_origin"] = "auto"
        updated += 1

    try:
        _write_registry(args.registry, registry)
    except OSError as exc:
        print(f"GAGAL: registry tidak dapat ditulis ({exc})", file=sys.stderr)
        return 1

    primary = sum(1 for r in registry
                  if isinstance(r, dict) and r.get("source_class") == "primary")
    secondary = sum(1 for r in registry
                    if isinstance(r, dict) and r.get("source_class") == "secondary")
    print(f"KELAS: {primary} primary, {secondary} secondary ({updated} diperbarui)")
    print(args.registry)
    return 0


