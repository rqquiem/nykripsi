def _load_registry(path: str) -> list[dict]:
    if not os.path.exists(path):
        return []
    with open(path, encoding="utf-8") as fh:
        text = fh.read().strip()
    if not text:
        return []
    data = json.loads(text)
    if not isinstance(data, list):
        raise ValueError("registry.json bukan array JSON")
    return data


def _write_registry(path: str, registry: list[dict]) -> None:
    directory = os.path.dirname(path)
    if directory:
        os.makedirs(directory, exist_ok=True)
    with open(path, "w", encoding="utf-8") as fh:
        fh.write(json.dumps(registry, ensure_ascii=False, indent=2) + "\n")


def _make_record(raw: dict, rtype: str, query: str, accessed: str) -> dict | None:
    url = (raw.get("url") or "").strip()
    if not url:
        return None
    return {
        "id": "",
        "type": rtype,
        "title": (raw.get("title") or "").strip(),
        "authors": _as_list(raw.get("authors")),
        "year": _year(raw.get("year")),
        "publisher": (raw.get("publisher") or "").strip() or None,
        "url": url,
        "doi": (raw.get("doi") or "").strip() or None,
        "accessed": accessed,
        "query": query,
        "backend": (raw.get("backend") or "").strip(),
        "source_class": default_class(rtype),
        "class_origin": "auto",
        "notes": "",
        "cite_key": None,
    }


def _dedupe(records: list[dict], registry: list[dict]) -> tuple[list[dict], int]:
    seen_urls = {(r.get("url") or "").lower() for r in registry if isinstance(r, dict)}
    seen_dois = {r.get("doi") for r in registry if isinstance(r, dict) and r.get("doi")}
    kept: list[dict] = []
    skipped = 0
    for rec in records:
        url = rec["url"].lower()
        doi = rec["doi"]
        if url in seen_urls or (doi and doi in seen_dois):
            skipped += 1
            continue
        seen_urls.add(url)
        if doi:
            seen_dois.add(doi)
        kept.append(rec)
    return kept, skipped


def _assign_ids(records: list[dict], registry: list[dict]) -> None:
    used = {r.get("id") for r in registry if isinstance(r, dict)}
    for rec in records:
        base = f"{rec['type']}-{rec['accessed']}-{slug(rec['title'])}"
        candidate = base
        n = 0
        while candidate in used:
            n += 1
            candidate = f"{base}-{n}"
        used.add(candidate)
        rec["id"] = candidate


