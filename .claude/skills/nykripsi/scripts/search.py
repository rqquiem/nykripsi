def _run_search(args, rtype: str, batch: Batch) -> int:
    try:
        registry = _load_registry(args.registry)
    except (OSError, ValueError) as exc:
        print(f"GAGAL: registry tidak dapat dibaca ({exc})", file=sys.stderr)
        return 1

    accessed = datetime.date.today().isoformat()
    override = getattr(args, "source_class", None)
    records: list[dict] = []
    for raw in batch.raw:
        rec = _make_record(raw, rtype, args.query, accessed)
        if rec is not None:
            if override:
                rec["source_class"] = override
                rec["class_origin"] = "manual"
            else:
                rec["source_class"] = default_class(rtype)
                rec["class_origin"] = "auto"
            records.append(rec)

    if not records:
        net = next(
            (e for e in batch.errors
             if isinstance(e, (urllib.error.URLError, TimeoutError, OSError))),
            None,
        )
        if net is not None:
            print(f"GAGAL: jaringan tidak tersedia ({net})", file=sys.stderr)
        else:
            print("GAGAL: tidak ada hasil", file=sys.stderr)
        return 1

    kept, skipped = _dedupe(records, registry)
    _assign_ids(kept, registry)

    if not args.no_save:
        try:
            _write_registry(args.registry, list(registry) + kept)
        except OSError as exc:
            print(f"GAGAL: registry tidak dapat ditulis ({exc})", file=sys.stderr)
            return 1

    if args.json:
        print(json.dumps(kept, ensure_ascii=False, indent=2))
        return 0

    for i, rec in enumerate(kept, start=1):
        authors = ", ".join(rec["authors"]) or "-"
        year = rec["year"] if rec["year"] is not None else "-"
        publisher = rec["publisher"] or "-"
        print(f"[{i}] {rec['type']} | {authors} ({year}). {rec['title']}. {publisher}. {rec['url']}")
    print(f"TAMBAH: {len(kept)} baru, {skipped} duplikat dilewati")
    print(args.registry)
    return 0


