class Batch:
    """Kumpulkan hasil beberapa backend; kesalahan per-backend bersifat non-fatal."""

    def __init__(self, to_stderr: bool = False):
        self.raw: list[dict] = []
        self.errors: list[Exception] = []
        self.backends: list[str] = []
        self.to_stderr = to_stderr

    def attempt(self, name: str, fn, *args, **kwargs) -> None:
        try:
            got = fn(*args, **kwargs) or []
        except (urllib.error.URLError, TimeoutError, OSError, Blocked, BackendError) as exc:
            self.errors.append(exc)
            return
        _log_provenance(name, self.to_stderr)
        self.backends.append(name)
        self.raw.extend(got)


