def _ddg_real_url(href: str) -> str:
    """Pulihkan URL asli dari pengalihan ``//duckduckgo.com/l/?uddg=<url>``."""
    href = html.unescape((href or "").strip())
    if not href:
        return ""
    if href.startswith("//"):
        href = "https:" + href
    parsed = urllib.parse.urlparse(href)
    if "duckduckgo.com" in parsed.netloc and parsed.path.startswith("/l/"):
        uddg = urllib.parse.parse_qs(parsed.query).get("uddg")
        if uddg:
            return html.unescape(uddg[0]).strip()
    return href

def _ddg_links(text: str) -> list[tuple[str, str]]:
    """Ambil pasangan ``(url, title)`` dari HTML hasil DuckDuckGo."""
    out: list[tuple[str, str]] = []
    seen: set[str] = set()
    for m in re.finditer(r'<a\b[^>]*class="[^"]*result__a[^"]*"[^>]*>(.*?)</a>',
                         text, re.S | re.I):
        tag, inner = m.group(0), m.group(1)
        href = re.search(r'href="([^"]+)"', tag, re.I)
        url = _ddg_real_url(href.group(1)) if href else ""
        if not url or not url.startswith("http"):
            continue
        title = html.unescape(re.sub(r"<[^>]+>", "", inner)).strip()
        if url.lower() in seen:
            continue
        seen.add(url.lower())
        out.append((url, title))
    return out

def fetch_duckduckgo(query: str, limit: int) -> list[dict]:
    params = urllib.parse.urlencode({"q": query})
    status, text = _get(DDG_HTML_URL + "?" + params)
    links = _ddg_links(text) if status == 200 else []
    if not links:  # fallback: lite.duckduckgo.com
        status, text = _get(DDG_LITE_URL + "?" + params)
        if status != 200:
            raise BackendError(f"HTTP {status}")
        links = _ddg_links(text)
    if not links:
        raise BackendError("tidak ada tautan hasil (diblokir?)")
    out: list[dict] = []
    for url, title in links[:limit]:
        out.append({
            "title": title,
            "url": url,
            "publisher": urllib.parse.urlparse(url).netloc or None,
            "year": None,
            "authors": [],
            "doi": None,
            "backend": "duckduckgo",
        })
    return out

def _ddg_topic_urls(related: list) -> list[tuple[str, str]]:
    """Ratakan ``RelatedTopics`` (termasuk ``Topics`` bersarang) -> ``(url, text)``."""
    out: list[tuple[str, str]] = []
    for topic in related or []:
        if not isinstance(topic, dict):
            continue
        nested = topic.get("Topics")
        if nested:
            out.extend(_ddg_topic_urls(nested))
            continue
        url = (topic.get("FirstURL") or "").strip()
        if url:
            out.append((url, (topic.get("Text") or "").strip()))
    return out

def fetch_ddg_instant(query: str, limit: int) -> list[dict]:
    url = DDG_INSTANT_URL + "?" + urllib.parse.urlencode({
        "q": query, "format": "json", "no_html": "1",
    })
    data = _json_get(url)
    out: list[dict] = []
    seen: set[str] = set()

    def add(url_rec: str, title: str) -> None:
        url_rec = (url_rec or "").strip()
        if not url_rec or url_rec.lower() in seen:
            return
        seen.add(url_rec.lower())
        out.append({
            "title": title,
            "url": url_rec,
            "publisher": urllib.parse.urlparse(url_rec).netloc or None,
            "year": None,
            "authors": [],
            "doi": None,
            "backend": "ddg-instant",
        })

    heading = (data.get("Heading") or "").strip()
    abstract = (data.get("AbstractText") or "").strip()
    add(data.get("AbstractURL"), heading or abstract)
    for url_rec, text in _ddg_topic_urls(data.get("RelatedTopics") or []):
        if len(out) >= limit:
            break
        add(url_rec, text)
    return out[:limit]

def fetch_wikipedia(query: str, limit: int) -> list[dict]:
    out: list[dict] = []
    for lang in ("en", "id"):
        url = WIKIPEDIA_API.format(lang=lang) + "?" + urllib.parse.urlencode({
            "action": "query", "list": "search", "srsearch": query,
            "format": "json", "srlimit": str(limit),
        })
        try:
            data = _json_get(url)
        except (urllib.error.URLError, TimeoutError, OSError, Blocked, BackendError):
            continue  # satu bahasa gagal -> lanjut bahasa lain
        for entry in ((data.get("query") or {}).get("search") or [])[:limit]:
            title = (entry.get("title") or "").strip()
            if not title:
                continue
            slug_title = urllib.parse.quote(title.replace(" ", "_"))
            out.append({
                "title": title,
                "url": f"https://{lang}.wikipedia.org/wiki/{slug_title}",
                "publisher": f"Wikipedia ({lang})",
                "year": None,
                "authors": [],
                "doi": None,
                "backend": "wikipedia",
            })
    if not out:
        raise BackendError("tidak ada hasil Wikipedia")
    return out

