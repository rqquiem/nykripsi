def fetch_scholar(query: str, limit: int) -> list[dict]:
    proc = subprocess.run(
        [sys.executable, SCHOLAR, "search", query, "--limit", str(limit), "--json"],
        capture_output=True,
        text=True,
    )
    if proc.returncode != 0:
        return []
    text = (proc.stdout or "").strip()
    if not text:
        return []
    try:
        data = json.loads(text)
    except json.JSONDecodeError:
        return []
    if not isinstance(data, list):
        return []

    out: list[dict] = []
    for rec in data:
        if not isinstance(rec, dict):
            continue
        doi = (rec.get("doi") or "").strip() or None
        url = (rec.get("url") or "").strip()
        if not url and doi:
            url = f"https://doi.org/{doi}"
        if not url:
            continue
        out.append({
            "title": (rec.get("title") or "").strip(),
            "url": url,
            "publisher": (rec.get("venue") or "").strip() or None,
            "year": _year(rec.get("year")),
            "authors": _as_list(rec.get("authors")),
            "doi": doi,
            "backend": (rec.get("source") or "scholar").strip(),
        })
    return out


