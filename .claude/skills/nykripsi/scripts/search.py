def _gdelt_request(url: str):
    """Satu permintaan GDELT dengan jeda 5 detik + satu retry 10 detik pada 429."""
    time.sleep(GDELT_DELAY)
    status, text = _get(url)
    if status == 429:
        time.sleep(GDELT_BACKOFF)
        status, text = _get(url)
    if status != 200:
        raise BackendError(f"HTTP {status}")
    try:
        return json.loads(text)
    except json.JSONDecodeError as exc:
        raise BackendError(f"JSON tidak valid ({exc})") from exc


def fetch_gdelt(query: str, limit: int) -> list[dict]:
    url = GDELT_URL + "?" + urllib.parse.urlencode({
        "query": query,
        "mode": "artlist",
        "maxrecords": str(limit),
        "format": "json",
        "sort": "datedesc",
    })
    data = _gdelt_request(url)
    out: list[dict] = []
    for art in (data.get("articles") or [])[:limit]:
        url_art = (art.get("url") or "").strip()
        if not url_art:
            continue
        seendate = art.get("seendate") or ""
        out.append({
            "title": (art.get("title") or "").strip(),
            "url": url_art,
            "publisher": (art.get("domain") or "").strip() or None,
            "year": _year(seendate[:4]),
            "authors": [],
            "doi": None,
            "backend": "gdelt",
        })
    return out


