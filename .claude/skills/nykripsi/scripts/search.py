def fetch_googlenews(query: str, limit: int) -> list[dict]:
    url = GOOGLENEWS_URL + "?" + urllib.parse.urlencode({
        "q": query,
        "hl": "en-US",
        "gl": "US",
        "ceid": "US:en",
    })
    status, text = _get(url)
    if status != 200:
        raise BackendError(f"HTTP {status}")
    try:
        root = ET.fromstring(text)
    except ET.ParseError as exc:
        raise BackendError(f"XML tidak valid ({exc})") from exc

    out: list[dict] = []
    for item in root.iter("item"):
        if len(out) >= limit:
            break
        link = (item.findtext("link") or "").strip()
        if not link:
            continue
        src = item.find("source")
        publisher = (src.text or "").strip() if src is not None else ""
        out.append({
            "title": (item.findtext("title") or "").strip(),
            "url": link,
            "publisher": publisher or None,
            "year": _year(item.findtext("pubDate")),
            "authors": [],
            "doi": None,
            "backend": "googlenews",
        })
    return out


