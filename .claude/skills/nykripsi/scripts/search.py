def _sec_url(doc_id, source: dict) -> str | None:
    """Bangun URL arsip dari ``_id`` = ``<accession>:<file>`` + ``ciks[0]``."""
    if not doc_id or ":" not in str(doc_id):
        return None
    accession, file_name = str(doc_id).split(":", 1)
    ciks = source.get("ciks") or []
    if not accession or not file_name or not ciks:
        return None
    cik = str(ciks[0]).strip()
    accession_nodash = accession.replace("-", "")
    if not cik or not accession_nodash:
        return None
    return (
        "https://www.sec.gov/Archives/edgar/data/"
        f"{cik}/{accession_nodash}/{file_name}"
    )


