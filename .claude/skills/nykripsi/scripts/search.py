def _get(url: str, headers: dict | None = None, timeout: int = 25):
    """GET ``url`` -> ``(status, text)``.

    Kesalahan HTTP dikembalikan sebagai ``(code, body)`` agar pemanggil dapat
    memutuskan apakah status tersebut fatal. Kesalahan jaringan (URLError)
    tetap dilempar.
    """
    hdrs = {"User-Agent": UA}
    if headers:
        hdrs.update(headers)
    req = urllib.request.Request(url, headers=hdrs)
    try:
        with urllib.request.urlopen(req, timeout=timeout) as resp:
            raw = resp.read()
            status = getattr(resp, "status", 200)
            charset = resp.headers.get_content_charset() or "utf-8"
            return status, raw.decode(charset, errors="replace")
    except urllib.error.HTTPError as exc:
        try:
            body = exc.read().decode("utf-8", errors="replace")
        except Exception:  # pragma: no cover - defensif
            body = ""
        return exc.code, body


def _json_get(url: str, headers: dict | None = None, timeout: int = 25):
    status, text = _get(url, headers=headers, timeout=timeout)
    if status != 200:
        raise BackendError(f"HTTP {status}")
    try:
        return json.loads(text)
    except json.JSONDecodeError as exc:
        raise BackendError(f"JSON tidak valid ({exc})") from exc


def slug(text: str) -> str:
    """ASCII-fold -> huruf kecil -> hanya ``[a-z0-9-]``."""
    folded = unicodedata.normalize("NFKD", text or "").encode("ascii", "ignore").decode("ascii")
    folded = folded.lower()
    folded = re.sub(r"[^a-z0-9]+", "-", folded).strip("-")
    return folded or "untitled"


def _year(value) -> int | None:
    if value is None:
        return None
    m = re.search(r"(1[89]\d{2}|20\d{2})", str(value))
    return int(m.group(1)) if m else None

def _year_from_epoch(value) -> int | None:
    """Tahun dari epoch detik (StackExchange/Invidious); None bila tidak valid."""
    if value is None:
        return None
    try:
        ts = int(value)
    except (TypeError, ValueError):
        return _year(value)
    if ts <= 0:
        return None
    return datetime.datetime.fromtimestamp(ts, datetime.timezone.utc).year


def _as_list(value) -> list[str]:
    if value is None:
        return []
    if isinstance(value, str):
        return [value] if value.strip() else []
    if isinstance(value, (list, tuple)):
        out: list[str] = []
        for item in value:
            if isinstance(item, dict):
                item = item.get("name") or item.get("title") or ""
            if item and str(item).strip():
                out.append(str(item).strip())
        return out
    return [str(value)]


def _text(value) -> str | None:
    """Ambil string dari nilai str / dict bersarang (mis. DataCite publisher)."""
    if value is None:
        return None
    if isinstance(value, str):
        return value.strip() or None
    if isinstance(value, dict):
        for key in ("name", "title", "value"):
            if key in value:
                got = _text(value[key])
                if got:
                    return got
    return None


