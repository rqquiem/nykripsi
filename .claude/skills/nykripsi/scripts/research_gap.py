def _render_table(records: list[dict]) -> list[str]:
    lines = [
        "| id | judul | verdict | kemiripan maks | diperiksa |",
        "| --- | --- | --- | --- | --- |",
    ]
    for rec in records:
        matches = [m for m in (rec.get("matches") or []) if isinstance(m, dict)]
        sim = max((m.get("similarity", 0.0) for m in matches), default=0.0)
        lines.append("| {id} | {judul} | {verdict} | {sim} | {checked} |".format(
            id=_cell(rec.get("id")), judul=_cell(rec.get("judul")),
            verdict=_cell(rec.get("verdict")), sim=f"{sim:.2f}",
            checked=_cell(rec.get("checked"))))
    return lines

def cmd_render(args) -> int:
    try:
        registry = _load_registry(args.registry)
    except (OSError, ValueError) as exc:
        print(f"GAGAL: registry tidak dapat dibaca ({exc})", file=sys.stderr)
        return 1

    lines = [HEADER, ""]
    if not registry:
        lines.append("_Belum ada judul._")
    else:
        groups: dict[str, list[dict]] = {}
        for rec in registry:
            if not isinstance(rec, dict):
                continue
            groups.setdefault(str(rec.get("status") or ""), []).append(rec)
        for status in STATUSES:
            if status not in groups:
                continue
            lines.append(f"## {status}")
            lines.append("")
            lines.extend(_render_table(groups[status]))
            lines.append("")

    directory = os.path.dirname(args.index)
    if directory:
        os.makedirs(directory, exist_ok=True)
    with open(args.index, "w", encoding="utf-8") as fh:
        fh.write("\n".join(lines).rstrip("\n") + "\n")
    print(args.index)
    return 0

