def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(
        prog="research_gap.py",
        description="Periksa ketersediaan judul penelitian dan susun laporan celah.",
    )
    sub = parser.add_subparsers(dest="command", required=True)

    p_check = sub.add_parser("check", help="periksa ketersediaan sebuah judul")
    p_check.add_argument("judul", help="judul penelitian yang diperiksa")
    p_check.add_argument("--limit", type=int, default=10, help="hasil maksimum per backend (default: 10)")
    p_check.add_argument("--threshold", type=float, default=DEFAULT_THRESHOLD,
                         help=f"ambang kemiripan (default: {DEFAULT_THRESHOLD})")
    p_check.add_argument("--registry", default=DEFAULT_REGISTRY,
                         help=f"berkas registry (default: {DEFAULT_REGISTRY})")
    p_check.add_argument("--json", action="store_true", help="cetak catatan baru sebagai JSON")
    p_check.add_argument("--no-save", action="store_true",
                         help="jangan ubah registry; hanya laporkan")
    p_check.add_argument("--email", default=None,
                         help="alamat surel polite pool Crossref/OpenAlex; env SCHOLAR_EMAIL")
    p_check.set_defaults(func=cmd_check)

    p_browser = sub.add_parser("browser-record", help="catat satu match hasil lintasan browser")
    p_browser.add_argument("judul", help="judul yang sudah diperiksa")
    p_browser.add_argument("--title", required=True, help="judul temuan")
    p_browser.add_argument("--url", required=True, help="URL temuan")
    p_browser.add_argument("--doi", default=None, help="DOI temuan")
    p_browser.add_argument("--year", default=None, help="tahun temuan")
    p_browser.add_argument("--backend", default="web", help="nama backend (default: web)")
    p_browser.add_argument("--registry", default=DEFAULT_REGISTRY,
                           help=f"berkas registry (default: {DEFAULT_REGISTRY})")
    p_browser.add_argument("--threshold", type=float, default=DEFAULT_THRESHOLD,
                           help=f"ambang kemiripan (default: {DEFAULT_THRESHOLD})")
    p_browser.add_argument("--json", action="store_true", help="cetak catatan sebagai JSON")
    p_browser.set_defaults(func=cmd_browser_record)

    p_gap = sub.add_parser("gap", help="tulis kerangka laporan celah penelitian")
    p_gap.add_argument("judul", help="judul yang sudah diperiksa")
    p_gap.add_argument("--registry", default=DEFAULT_REGISTRY,
                       help=f"berkas registry (default: {DEFAULT_REGISTRY})")
    p_gap.add_argument("--out", default=None, help="berkas keluaran (default: research/gap-<slug>.md)")
    p_gap.add_argument("--prior", action="append", default=None,
                       help="penelitian terdahulu manual: \"TITLE|URL|WEAKNESS|ANGLE\" (bisa diulang)")
    p_gap.set_defaults(func=cmd_gap)

    p_render = sub.add_parser("render", help="tulis ulang research/index.md dari registry")
    p_render.add_argument("--registry", default=DEFAULT_REGISTRY,
                          help=f"berkas registry (default: {DEFAULT_REGISTRY})")
    p_render.add_argument("--index", default=DEFAULT_INDEX,
                          help=f"berkas indeks (default: {DEFAULT_INDEX})")
    p_render.set_defaults(func=cmd_render)

    return parser

def main(argv: list[str] | None = None) -> int:
    parser = build_parser()
    args = parser.parse_args(argv)
    try:
        return args.func(args)
    except urllib.error.URLError as exc:
        print(f"GAGAL: jaringan tidak tersedia ({exc})", file=sys.stderr)
        return 1
    except KeyboardInterrupt:
        return 130

if __name__ == "__main__":
    sys.exit(main())
