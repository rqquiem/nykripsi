def make_match(title, url, doi, year, backend: str, judul_norm: str) -> dict | None:
    """Bangun objek match; ``None`` bila judul atau URL kosong."""
    t = (title or "").strip()
    u = (url or "").strip()
    if not t or not u:
        return None
    nt = norm_title(t)
    kind = "exact" if nt == judul_norm else "similar"
    sim = 1.0 if kind == "exact" else similarity(nt, judul_norm)
    return {
        "title": t,
        "url": u,
        "doi": (doi or None),
        "year": year if isinstance(year, int) else _int(year),
        "backend": backend,
        "similarity": sim,
        "kind": kind,
    }

def dedupe_matches(matches: list[dict]) -> list[dict]:
    """Buang duplikat judul (ternormalisasi), simpan kemiripan tertinggi."""
    best: dict[str, dict] = {}
    for m in matches:
        key = norm_title(m.get("title", ""))
        if not key:
            continue
        cur = best.get(key)
        if cur is None or m.get("similarity", 0.0) > cur.get("similarity", 0.0):
            best[key] = m
    return list(best.values())

def _offending(verdict: str, matches: list[dict]) -> dict | None:
    """Match paling mirip yang menyebabkan verdict memblokir."""
    if not matches:
        return None
    if verdict == "duplicate":
        exact = [m for m in matches if m.get("kind") == "exact"]
        pool = exact or matches
    else:
        pool = matches
    return max(pool, key=lambda m: m.get("similarity", 0.0))

