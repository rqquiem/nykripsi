# Utilitas umum
# ---------------------------------------------------------------------------

def _log_provenance(name: str, to_stderr: bool = False) -> None:
    """Cetak baris provenance ``# backend: <name>``."""
    stream = sys.stderr if to_stderr else sys.stdout
    print(f"# backend: {name}", file=stream)

def _get(url: str, headers: dict | None = None, timeout: int = 25):
    """GET ``url`` -> ``(status, text)``.

    Kesalahan HTTP dikembalikan sebagai ``(code, body)`` agar pemanggil dapat
    memutuskan apakah status tersebut fatal. Kesalahan jaringan (URLError)
    tetap dilempar.
    """
    hdrs = {"User-Agent": UA}
    if headers:
        hdrs.update(headers)
    req = urllib.request.Request(url, headers=hdrs)
    try:
        with urllib.request.urlopen(req, timeout=timeout) as resp:
            raw = resp.read()
            status = getattr(resp, "status", 200)
            charset = resp.headers.get_content_charset() or "utf-8"
            return status, raw.decode(charset, errors="replace")
    except urllib.error.HTTPError as exc:
        try:
            body = exc.read().decode("utf-8", errors="replace")
        except Exception:  # pragma: no cover - defensif
            body = ""
        return exc.code, body

def _json_get(url: str, headers: dict | None = None, timeout: int = 25):
    status, text = _get(url, headers=headers, timeout=timeout)
    if status != 200:
        raise BackendError(f"HTTP {status}")
    try:
        return json.loads(text)
    except json.JSONDecodeError as exc:
        raise BackendError(f"JSON tidak valid ({exc})") from exc

def _fold(text: str) -> str:
    """ASCII-fold: NFKD lalu buang aksara non-ASCII."""
    return unicodedata.normalize("NFKD", text or "").encode("ascii", "ignore").decode("ascii")

def norm_title(text: str) -> str:
    """Normalisasi judul: ASCII-fold -> huruf kecil -> hanya ``[a-z0-9]`` + spasi tunggal."""
    folded = _fold(text).lower()
    folded = re.sub(r"[^a-z0-9]+", " ", folded).strip()
    return folded

def slug(text: str) -> str:
    """ASCII-fold -> huruf kecil -> hanya ``[a-z0-9-]``."""
    folded = _fold(text).lower()
    folded = re.sub(r"[^a-z0-9]+", "-", folded).strip("-")
    return folded or "untitled"

def similarity(a_norm: str, b_norm: str) -> float:
    """Kemiripan Jaccard atas himpunan token dari dua judul ternormalisasi."""
    ta = set((a_norm or "").split())
    tb = set((b_norm or "").split())
    if not ta or not tb:
        return 0.0
    return len(ta & tb) / len(ta | tb)

def compute_verdict(matches: list[dict], threshold: float) -> str:
    """Tentukan verdict dari kumpulan match."""
    if any(m.get("kind") == "exact" for m in matches):
        return "duplicate"
    if matches and max(m.get("similarity", 0.0) for m in matches) >= threshold:
        return "too-similar"
    return "available"

def _int(value) -> int | None:
    """Ambil tahun dari nilai apa pun; ``None`` bila tidak ada."""
    if value is None:
        return None
    m = re.search(r"(1[89]\d{2}|20\d{2})", str(value))
    return int(m.group(1)) if m else None

def _cell(value) -> str:
    """Rapikan isi sel tabel Markdown."""
    return str(value if value is not None else "").replace("|", "\\|").replace("\n", " ").strip()

