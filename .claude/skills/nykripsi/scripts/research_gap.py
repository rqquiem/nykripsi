def cmd_check(args) -> int:
    try:
        registry = _load_registry(args.registry)
    except (OSError, ValueError) as exc:
        print(f"GAGAL: registry tidak dapat dibaca ({exc})", file=sys.stderr)
        return 1

    judul = args.judul
    judul_norm = norm_title(judul)
    checked = datetime.date.today().isoformat()
    threshold = args.threshold
    matches = _collect(judul, judul_norm, args.limit, _email(args), registry, args.json)
    verdict = compute_verdict(matches, threshold)

    record = {
        "id": _assign_id(judul, checked, registry),
        "judul": judul,
        "judul_norm": judul_norm,
        "status": "selected" if verdict == "available" else "rejected",
        "verdict": verdict,
        "threshold": threshold,
        "origin": "auto",
        "checked": checked,
        "query": judul,
        "matches": matches,
        "notes": "",
    }

    if not args.no_save:
        if verdict == "available":
            for rec in registry:
                if isinstance(rec, dict) and rec.get("status") == "selected":
                    rec["status"] = "candidate"
        registry.append(record)
        try:
            _write_registry(args.registry, registry)
        except OSError as exc:
            print(f"GAGAL: registry tidak dapat ditulis ({exc})", file=sys.stderr)
            return 1

    if args.json:
        print(json.dumps(record, ensure_ascii=False, indent=2))
        return 0 if verdict == "available" else 1

    if verdict == "available":
        print(f"TERSEDIA: {judul} ({len(matches)} kandidat diperiksa, "
              f"kemiripan maks {_max_sim(matches):.2f})")
        print(args.registry)
        return 0
    print(_blocked_message(verdict, matches, threshold), file=sys.stderr)
    return 1

