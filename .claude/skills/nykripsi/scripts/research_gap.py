def cmd_browser_record(args) -> int:
    try:
        registry = _load_registry(args.registry)
    except (OSError, ValueError) as exc:
        print(f"GAGAL: registry tidak dapat dibaca ({exc})", file=sys.stderr)
        return 1

    target_norm = norm_title(args.judul)
    rec = None
    for item in registry:
        if isinstance(item, dict) and item.get("judul_norm") == target_norm:
            rec = item
            break
    if rec is None:
        print(f"GAGAL: judul belum diperiksa: {args.judul}", file=sys.stderr)
        return 1

    judul_norm = rec.get("judul_norm") or norm_title(rec.get("judul", ""))
    matches = rec.get("matches")
    if not isinstance(matches, list):
        matches = []
        rec["matches"] = matches

    nt = norm_title(args.title)
    present = {norm_title(m.get("title", "")) for m in matches if isinstance(m, dict)}
    if nt and nt not in present:
        m = make_match(args.title, args.url, args.doi, args.year, args.backend, judul_norm)
        if m is not None:
            matches.append(m)

    threshold = args.threshold
    verdict = compute_verdict(matches, threshold)
    rec["origin"] = "browser"
    rec["threshold"] = threshold
    rec["verdict"] = verdict
    if verdict != "available" and rec.get("status") == "selected":
        rec["status"] = "rejected"

    try:
        _write_registry(args.registry, registry)
    except OSError as exc:
        print(f"GAGAL: registry tidak dapat ditulis ({exc})", file=sys.stderr)
        return 1

    if args.json:
        print(json.dumps(rec, ensure_ascii=False, indent=2))
        return 0 if verdict == "available" else 1

    if verdict != "available":
        print(_blocked_message(verdict, matches, threshold), file=sys.stderr)
        return 1
    print(f"DIPERBARUI: {rec.get('judul')} -> {verdict}")
    return 0

