def _parse_prior(value: str) -> tuple[str, str, str, str]:
    parts = (value or "").split("|")
    parts += [""] * (4 - len(parts))
    return tuple(p.strip() for p in parts[:4])  # type: ignore[return-value]

def cmd_gap(args) -> int:
    try:
        registry = _load_registry(args.registry)
    except (OSError, ValueError) as exc:
        print(f"GAGAL: registry tidak dapat dibaca ({exc})", file=sys.stderr)
        return 1

    target_norm = norm_title(args.judul)
    rec = None
    for item in registry:
        if isinstance(item, dict) and item.get("judul_norm") == target_norm:
            rec = item
            break
    if rec is None:
        print(f"GAGAL: judul belum diperiksa: {args.judul}", file=sys.stderr)
        return 1

    judul = rec.get("judul") or args.judul
    matches = [m for m in (rec.get("matches") or []) if isinstance(m, dict)]
    matches.sort(key=lambda m: m.get("similarity", 0.0), reverse=True)

    rows: list[str] = []
    weaknesses: list[str] = []
    angles: list[str] = []
    n = 0
    for m in matches:
        n += 1
        year = m.get("year")
        rows.append("| {n} | {title} | {year} | {backend} | {sim} |".format(
            n=n, title=_cell(m.get("title")), year=_cell(year if year is not None else "-"),
            backend=_cell(m.get("backend")), sim=f"{m.get('similarity', 0.0):.2f}"))
    for raw in (args.prior or []):
        title, url, weakness, angle = _parse_prior(raw)
        n += 1
        rows.append("| {n} | {title} | - | {url} | - |".format(
            n=n, title=_cell(title), url=_cell(url)))
        if weakness:
            weaknesses.append(weakness)
        if angle:
            angles.append(angle)

    lines = [
        f"# Celah Penelitian: {judul}",
        "",
        "<!-- Dibuat oleh research_gap.py gap. Isi setiap bagian; jangan hapus kepala bagian. -->",
        "",
        "## Penelitian Terdahulu",
        "",
        "| # | Judul | Tahun | Sumber | Kemiripan |",
        "| --- | --- | --- | --- | --- |",
    ]
    lines.extend(rows if rows else ["| - | - | - | - | - |"])
    lines += ["", "## Kelemahan Penelitian Terdahulu", ""]
    lines += [f"- {w}" for w in weaknesses] if weaknesses else ["- …"]
    lines += ["", "## Sudut Pandang Berbeda", ""]
    lines += [f"- {a}" for a in angles] if angles else ["- …"]
    lines += [
        "",
        "## Rumusan Celah Penelitian",
        "",
        "…",
        "",
        "## Kebaruan yang Diusulkan",
        "",
        "…",
    ]

    out = args.out or os.path.join("research", f"gap-{slug(judul)}.md")
    directory = os.path.dirname(out)
    if directory:
        os.makedirs(directory, exist_ok=True)
    with open(out, "w", encoding="utf-8") as fh:
        fh.write("\n".join(lines).rstrip("\n") + "\n")
    print(out)
    return 0

