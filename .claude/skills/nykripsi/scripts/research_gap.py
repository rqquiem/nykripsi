def fetch_crossref(judul: str, limit: int, email: str | None = None) -> list[dict]:
    params = {
        "query.bibliographic": judul,
        "rows": str(limit),
        "select": "DOI,title,author,issued,container-title",
    }
    if email:
        params["mailto"] = email
    data = _json_get(CROSSREF_URL + "?" + urllib.parse.urlencode(params))
    out: list[dict] = []
    items = ((data.get("message") or {}).get("items") or [])[:limit]
    for item in items:
        titles = item.get("title") or []
        title = (titles[0] if titles else "") or ""
        doi = (item.get("DOI") or "").strip()
        url = f"https://doi.org/{doi}" if doi else ""
        parts = (item.get("issued") or {}).get("date-parts") or []
        year = _int(parts[0][0]) if parts and parts[0] else None
        out.append({"title": title, "url": url, "doi": doi or None, "year": year,
                    "backend": "crossref"})
    return out

# ---------------------------------------------------------------------------
# Backend: OpenAlex
# ---------------------------------------------------------------------------

def fetch_openalex(judul: str, limit: int, email: str | None = None) -> list[dict]:
    params = {
        "search": judul,
        "per-page": str(limit),
        "select": "id,doi,title,publication_year",
    }
    if email:
        params["mailto"] = email
    data = _json_get(OPENALEX_URL + "?" + urllib.parse.urlencode(params))
    out: list[dict] = []
    for work in (data.get("results") or [])[:limit]:
        title = (work.get("title") or "").strip()
        doi = (work.get("doi") or "").strip()
        if doi:
            doi = re.sub(r"^https?://doi\.org/", "", doi)
        url = (work.get("doi") or work.get("id") or "").strip()
        out.append({"title": title, "url": url, "doi": doi or None,
                    "year": _int(work.get("publication_year")), "backend": "openalex"})
    return out

# ---------------------------------------------------------------------------
# Backend: scholar.py
# ---------------------------------------------------------------------------

def fetch_scholar(judul: str, limit: int) -> list[dict]:
    proc = subprocess.run(
        [sys.executable, SCHOLAR, "search", judul, "--limit", str(limit), "--json"],
        capture_output=True, text=True,
    )
    if proc.returncode != 0:
        raise BackendError(f"scholar.py keluar dengan kode {proc.returncode}")
    try:
        data = json.loads(proc.stdout or "[]")
    except json.JSONDecodeError as exc:
        raise BackendError(f"JSON tidak valid ({exc})") from exc
    if not isinstance(data, list):
        raise BackendError("scholar.py bukan array JSON")
    out: list[dict] = []
    for rec in data:
        if not isinstance(rec, dict):
            continue
        out.append({
            "title": (rec.get("title") or "").strip(),
            "url": (rec.get("url") or "").strip(),
            "doi": (rec.get("doi") or None),
            "year": _int(rec.get("year")),
            "backend": (rec.get("source") or "scholar"),
        })
    return out

# ---------------------------------------------------------------------------
# Backend: registry (judul.json sendiri)
# ---------------------------------------------------------------------------

def fetch_registry(registry: list[dict]) -> list[dict]:
    """Setiap catatan lama menyumbang satu match agar judul tak bertabrakan."""
    out: list[dict] = []
    for rec in registry:
        if not isinstance(rec, dict):
            continue
        title = rec.get("judul")
        rid = rec.get("id")
        if not title or not rid:
            continue
        out.append({"title": title, "url": f"registry:{rid}", "doi": None, "year": None,
                    "backend": "registry"})
    return out

