class Batch:
    """Kumpulkan hasil beberapa backend; kesalahan per-backend bersifat non-fatal."""

    def __init__(self, to_stderr: bool = False):
        self.raw: list[dict] = []
        self.errors: list[Exception] = []
        self.backends: list[str] = []
        self.to_stderr = to_stderr

    def attempt(self, name: str, fn, *args, **kwargs) -> None:
        try:
            got = fn(*args, **kwargs) or []
        except (urllib.error.URLError, TimeoutError, OSError, BackendError) as exc:
            self.errors.append(exc)
            return
        _log_provenance(name, self.to_stderr)
        self.backends.append(name)
        self.raw.extend(got)

# ---------------------------------------------------------------------------
# Registry + catatan
# ---------------------------------------------------------------------------

def _load_registry(path: str) -> list[dict]:
    if not os.path.exists(path):
        return []
    with open(path, encoding="utf-8") as fh:
        text = fh.read().strip()
    if not text:
        return []
    data = json.loads(text)
    if not isinstance(data, list):
        raise ValueError("judul.json bukan array JSON")
    return data

def _write_registry(path: str, registry: list[dict]) -> None:
    directory = os.path.dirname(path)
    if directory:
        os.makedirs(directory, exist_ok=True)
    with open(path, "w", encoding="utf-8") as fh:
        fh.write(json.dumps(registry, ensure_ascii=False, indent=2) + "\n")

def _assign_id(judul: str, checked: str, registry: list[dict]) -> str:
    used = {r.get("id") for r in registry if isinstance(r, dict)}
    base = f"judul-{checked}-{slug(judul)}"
    candidate = base
    n = 0
    while candidate in used:
        n += 1
        candidate = f"{base}-{n}"
    return candidate

def _email(args) -> str | None:
    return getattr(args, "email", None) or os.environ.get("SCHOLAR_EMAIL") or None

def _collect(judul: str, judul_norm: str, limit: int, email: str | None,
             registry: list[dict], to_stderr: bool) -> list[dict]:
    batch = Batch(to_stderr=to_stderr)
    batch.attempt("registry", fetch_registry, registry)
    batch.attempt("crossref", fetch_crossref, judul, limit, email)
    batch.attempt("openalex", fetch_openalex, judul, limit, email)
    batch.attempt("scholar", fetch_scholar, judul, limit)
    matches: list[dict] = []
    for raw in batch.raw:
        m = make_match(raw.get("title"), raw.get("url"), raw.get("doi"), raw.get("year"),
                       raw.get("backend") or "", judul_norm)
        if m is not None:
            matches.append(m)
    return dedupe_matches(matches)

def _max_sim(matches: list[dict]) -> float:
    return max((m.get("similarity", 0.0) for m in matches), default=0.0)

def _blocked_message(verdict: str, matches: list[dict], threshold: float) -> str:
    off = _offending(verdict, matches)
    title = (off or {}).get("title", "")
    url = (off or {}).get("url", "")
    if verdict == "duplicate":
        return f"GAGAL: judul duplikat: {title} ({url})"
    sim = (off or {}).get("similarity", 0.0)
    return f"GAGAL: judul terlalu mirip ({sim:.2f} >= {threshold:.2f}): {title} ({url})"

